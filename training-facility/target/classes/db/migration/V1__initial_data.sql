DROP TABLE IF EXISTS tb_registration;
DROP TABLE IF EXISTS tb_session;
DROP TABLE IF EXISTS tb_participant;
DROP TABLE IF EXISTS tb_coach;

CREATE TABLE tb_participant (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL
);

CREATE TABLE tb_coach (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL
);

CREATE TABLE tb_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coach_id BIGINT NOT NULL REFERENCES tb_coach(id) ON DELETE RESTRICT,
  start_time timestamptz NOT NULL,
  end_time timestamptz NOT NULL,
  capacity BIGINT,
  location TEXT,
  status TEXT NOT NULL,
  version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE tb_registration (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id BIGINT NOT NULL REFERENCES tb_participant(id) ON DELETE CASCADE,
  session_id BIGINT NOT NULL REFERENCES tb_session(id) ON DELETE CASCADE,
  registered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  status TEXT,
  CONSTRAINT uq_participant_session UNIQUE (participant_id, session_id)
);

